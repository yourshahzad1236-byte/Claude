    REASON             VARCHAR2(500)  NOT NULL,
    STATUS             VARCHAR2(10)   DEFAULT 'SUBMITTED' NOT NULL,
    APPROVER_ID        NUMBER(10),
    ESCALATED_ON       DATE,
    DECIDED_BY         VARCHAR2(100),
    DECIDED_ON         DATE,
    DECISION_COMMENT   VARCHAR2(500),
    ROW_VERSION        NUMBER(10)     DEFAULT 1 NOT NULL,
    CREATED_BY         VARCHAR2(100)  DEFAULT NVL(SYS_CONTEXT('APEX$SESSION','APP_USER'), USER) NOT NULL,
