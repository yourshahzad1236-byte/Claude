    (CASE WHEN STATUS IN ('SUBMITTED','ESCALATED','APPROVED') THEN EMPLOYEE_ID END,
     CASE WHEN STATUS IN ('SUBMITTED','ESCALATED','APPROVED') THEN TRIP_DATE END,
     CASE WHEN STATUS IN ('SUBMITTED','ESCALATED','APPROVED') THEN TRIP_DIRECTION END);
CREATE INDEX HRD.IDX_TRADJ_APPROVER_STATUS ON HRD.HRD_TRANSPORT_ADJ_REQUEST (APPROVER_ID, STATUS);
CREATE INDEX HRD.IDX_TRADJ_EMP_DATE ON HRD.HRD_TRANSPORT_ADJ_REQUEST (EMPLOYEE_ID, TRIP_DATE);

