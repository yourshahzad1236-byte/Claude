-- DS-01  Policy / formula versions (all open business rules are settings here)
--------------------------------------------------------------------------------
CREATE TABLE HRD.HRD_TRANSPORT_FORMULA_MST
(
    FORMULA_ID            NUMBER(10)     DEFAULT HRD.TRANSPORT_FORMULA_SEQ.NEXTVAL NOT NULL,
    VERSION_NO            NUMBER(5)      NOT NULL,
    EFFECTIVE_FROM        DATE           NOT NULL,
    ALLOWANCE_AMOUNT      NUMBER(10,2)   NOT NULL,
    ALLOWANCE_BASE_DAYS   NUMBER(2)      NOT NULL,
    FORMULA_TYPE          VARCHAR2(20)   DEFAULT 'FUEL_INDEXED' NOT NULL,
    BASE_TRIP_COST        NUMBER(10,2)   NOT NULL,
    REF_FUEL_PRICE        NUMBER(10,2)   NOT NULL,
    SETTLEMENT_MODE       VARCHAR2(20)   NOT NULL,
    PRORATION_MODE        VARCHAR2(20)   NOT NULL,
    DEDUCTION_BASIS       VARCHAR2(10)   NOT NULL,
    SINGLE_SWIPE_RULE     VARCHAR2(20)   NOT NULL,
    DIRECTION_MODE        VARCHAR2(10)   NOT NULL,
    ROUTING_MODE          VARCHAR2(20)   NOT NULL,
    LATE_PRICE_MODE       VARCHAR2(20)   DEFAULT 'RECALCULATE' NOT NULL,
    REPEAT_SWIPE_MINUTES  NUMBER(3)      DEFAULT 2 NOT NULL,
    ESCALATION_DAYS       NUMBER(2)      DEFAULT 2 NOT NULL,
    ADJ_WINDOW_DAYS       NUMBER(3),
    PAYROLL_CUTOFF_DAY    NUMBER(2),
    STATUS                VARCHAR2(10)   DEFAULT 'PENDING' NOT NULL,
    MAKER_BY              VARCHAR2(100)  NOT NULL,
    CHECKER_BY            VARCHAR2(100),
    CHECKED_ON            DATE,
    CREATED_BY            VARCHAR2(100)  DEFAULT NVL(SYS_CONTEXT('APEX$SESSION','APP_USER'), USER) NOT NULL,
    CREATED_ON            DATE           DEFAULT SYSDATE NOT NULL,
    MODIFIED_BY           VARCHAR2(100),
    MODIFIED_ON           DATE,
    CONSTRAINT PK_HRD_TRANSPORT_FORMULA_MST PRIMARY KEY (FORMULA_ID),
    CONSTRAINT UK_TRFORMULA_VERSION UNIQUE (VERSION_NO),
    CONSTRAINT CK_TRFORMULA_AMOUNTS CHECK (ALLOWANCE_AMOUNT > 0 AND BASE_TRIP_COST > 0 AND REF_FUEL_PRICE > 0),
    CONSTRAINT CK_TRFORMULA_BASE_DAYS CHECK (ALLOWANCE_BASE_DAYS BETWEEN 1 AND 31),
    CONSTRAINT CK_TRFORMULA_TYPE CHECK (FORMULA_TYPE IN ('FUEL_INDEXED','FIXED')),
    CONSTRAINT CK_TRFORMULA_SETTLEMENT CHECK (SETTLEMENT_MODE IN ('CAP_ZERO','SCALE_ALLOWANCE','DERIVE_TRIP_COST','RECOVER_EXCESS')),
    CONSTRAINT CK_TRFORMULA_PRORATION CHECK (PRORATION_MODE IN ('NONE','CALENDAR_DAYS','WORKING_DAYS')),
    CONSTRAINT CK_TRFORMULA_BASIS CHECK (DEDUCTION_BASIS IN ('PER_TRIP','PER_SWIPE')),
    CONSTRAINT CK_TRFORMULA_SINGLE CHECK (SINGLE_SWIPE_RULE IN ('COUNT_TRIP','REVIEW')),
    CONSTRAINT CK_TRFORMULA_DIRECTION CHECK (DIRECTION_MODE IN ('TERMINAL','SEQUENCE')),
    CONSTRAINT CK_TRFORMULA_ROUTING CHECK (ROUTING_MODE IN ('SUPERVISOR','COORDINATOR','BOTH_FIRST_WINS')),
    CONSTRAINT CK_TRFORMULA_LATE_PRICE CHECK (LATE_PRICE_MODE IN ('RECALCULATE','FROM_ENTRY')),
    CONSTRAINT CK_TRFORMULA_REPEAT CHECK (REPEAT_SWIPE_MINUTES BETWEEN 0 AND 120),
    CONSTRAINT CK_TRFORMULA_ESCALATION CHECK (ESCALATION_DAYS BETWEEN 1 AND 30),
    CONSTRAINT CK_TRFORMULA_CUTOFF CHECK (PAYROLL_CUTOFF_DAY IS NULL OR PAYROLL_CUTOFF_DAY BETWEEN 1 AND 31),
    CONSTRAINT CK_TRFORMULA_STATUS CHECK (STATUS IN ('PENDING','ACTIVE','REJECTED','RETIRED')),
    CONSTRAINT CK_TRFORMULA_MAKER_CHECKER CHECK (CHECKER_BY IS NULL OR CHECKER_BY <> MAKER_BY)
);
COMMENT ON TABLE  HRD.HRD_TRANSPORT_FORMULA_MST IS 'Versioned transport allowance policy: allowance, deduction formula and the settings that implement open business rules (SRS Q-02, Q-04, Q-05, Q-07, Q-10, Q-11, Q-14, Q-15, Q-16). Maker-checker activation.';
COMMENT ON COLUMN HRD.HRD_TRANSPORT_FORMULA_MST.BASE_TRIP_COST IS 'Per-trip cost at REF_FUEL_PRICE (reference 500 PKR). FUEL_INDEXED cost = ROUND(BASE_TRIP_COST * fuel price / REF_FUEL_PRICE).';
COMMENT ON COLUMN HRD.HRD_TRANSPORT_FORMULA_MST.SETTLEMENT_MODE IS 'SRS Q-07: CAP_ZERO (a), SCALE_ALLOWANCE (b), DERIVE_TRIP_COST (c), RECOVER_EXCESS (salary recovery, needs policy basis).';
COMMENT ON COLUMN HRD.HRD_TRANSPORT_FORMULA_MST.DIRECTION_MODE IS 'SRS Q-15: TERMINAL = direction fixed per reader; SEQUENCE = derived from the order of swipes.';
COMMENT ON COLUMN HRD.HRD_TRANSPORT_FORMULA_MST.ROUTING_MODE IS 'SRS Q-11: who approves missed-swipe adjustments.';
COMMENT ON COLUMN HRD.HRD_TRANSPORT_FORMULA_MST.LATE_PRICE_MODE IS 'SRS Q-16: RECALCULATE open-period trips when a price is activated late, or apply FROM_ENTRY only.';
CREATE UNIQUE INDEX HRD.IDX_TRFORMULA_ACTIVE_FROM ON HRD.HRD_TRANSPORT_FORMULA_MST (CASE WHEN STATUS = 'ACTIVE' THEN EFFECTIVE_FROM END);

