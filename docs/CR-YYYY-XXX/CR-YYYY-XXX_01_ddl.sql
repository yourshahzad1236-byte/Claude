    CONSTRAINT CK_TRTRIP_STATUS CHECK (TRIP_STATUS IN ('VALID','INCOMPLETE','RATE_MISSING','REVERSED')),
    CONSTRAINT CK_TRTRIP_AMOUNT CHECK (DEDUCTION_AMOUNT IS NULL OR DEDUCTION_AMOUNT >= 0),
    CONSTRAINT CK_TRTRIP_MANUAL_REF CHECK (TRIP_SOURCE = 'RFID' OR ADJ_REQUEST_ID IS NOT NULL)
);
COMMENT ON TABLE  HRD.HRD_TRANSPORT_TRIP_TRN IS 'Trips derived from swipes (RFID) or approved adjustments (MANUAL), with the deduction, fuel price and formula version used (SRS FR-006, FR-007, FR-013).';
COMMENT ON COLUMN HRD.HRD_TRANSPORT_TRIP_TRN.TRIP_STATUS IS 'VALID counts toward deductions. INCOMPLETE = single swipe awaiting review (Q-02). RATE_MISSING = no effective fuel price (FR-007 AC3).';
