    (CASE WHEN TRIP_STATUS <> 'REVERSED' AND TRIP_DIRECTION <> 'UNKNOWN' THEN EMPLOYEE_ID END,
     CASE WHEN TRIP_STATUS <> 'REVERSED' AND TRIP_DIRECTION <> 'UNKNOWN' THEN TRIP_DATE END,
     CASE WHEN TRIP_STATUS <> 'REVERSED' AND TRIP_DIRECTION <> 'UNKNOWN' THEN TRIP_DIRECTION END,
     CASE WHEN TRIP_STATUS <> 'REVERSED' AND TRIP_DIRECTION <> 'UNKNOWN' THEN START_TIME END);

