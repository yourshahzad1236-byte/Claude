BEFORE DELETE ON HRD.HRD_TRANSPORT_SWIPE_TRN
BEGIN
    RAISE_APPLICATION_ERROR(-20720, 'Transport swipes cannot be deleted. Reverse the swipe with a reason instead.');
END TRG_TRANSPORT_SWIPE_BD;
