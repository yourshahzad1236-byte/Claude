    CONSTRAINT CK_TRADJ_REASON CHECK (LENGTH(TRIM(REASON)) >= 10),
    CONSTRAINT CK_TRADJ_STATUS CHECK (STATUS IN ('SUBMITTED','ESCALATED','APPROVED','REJECTED','CANCELLED')),
