-- LEAVE_REQ_SEQ is used by the existing TRG_LEAVE_REQUEST_BI but is absent from the schema snapshot (Q-15).
DECLARE
  V_CNT   NUMBER;
  V_START NUMBER;
BEGIN
  SELECT COUNT(*) INTO V_CNT FROM ALL_SEQUENCES WHERE SEQUENCE_OWNER = 'HRD' AND SEQUENCE_NAME = 'LEAVE_REQ_SEQ';
  IF V_CNT = 0 THEN
    SELECT NVL(MAX(LEAVE_REQUEST_ID), 0) + 1 INTO V_START FROM HRD.HRD_LEAVE_REQUEST;
    EXECUTE IMMEDIATE 'CREATE SEQUENCE HRD.LEAVE_REQ_SEQ START WITH ' || TO_CHAR(V_START) || ' INCREMENT BY 1 NOCYCLE';
  END IF;
END;
/
