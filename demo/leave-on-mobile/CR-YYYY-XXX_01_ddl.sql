DECLARE
  PROCEDURE P_ADD_COL (P_TABLE IN VARCHAR2, P_COL IN VARCHAR2, P_DEF IN VARCHAR2) IS
    V_CNT NUMBER;
  BEGIN
    SELECT COUNT(*) INTO V_CNT FROM ALL_TAB_COLUMNS
     WHERE OWNER = 'HRD' AND TABLE_NAME = P_TABLE AND COLUMN_NAME = P_COL;
    IF V_CNT = 0 THEN
      EXECUTE IMMEDIATE 'ALTER TABLE HRD.' || P_TABLE || ' ADD (' || P_COL || ' ' || P_DEF || ')';
    END IF;
  END P_ADD_COL;
  PROCEDURE P_TRY (P_SQL IN VARCHAR2) IS
  BEGIN
    EXECUTE IMMEDIATE P_SQL;
  EXCEPTION
    WHEN OTHERS THEN
      -- ignore "already exists" style errors so the script can be re-run
      IF SQLCODE NOT IN (-955, -1408, -2260, -2261, -2264, -2275) THEN RAISE; END IF;
  END P_TRY;
BEGIN
  -- DS-04 HRD_EMPLOYEE_MST
  P_ADD_COL('HRD_EMPLOYEE_MST', 'WARD_ID', 'NUMBER(6)');
  P_TRY('ALTER TABLE HRD.HRD_EMPLOYEE_MST ADD CONSTRAINT FK_EMP_WARD FOREIGN KEY (WARD_ID) REFERENCES HRD.HRD_WARD_MST (WARD_ID)');
  P_TRY('CREATE INDEX HRD.IDX_EMP_WARD ON HRD.HRD_EMPLOYEE_MST (WARD_ID)');

  -- DS-05 HRD_LEAVE_REQUEST
  P_ADD_COL('HRD_LEAVE_REQUEST', 'NO_OF_DAYS',           'NUMBER(5)');
  P_ADD_COL('HRD_LEAVE_REQUEST', 'WARD_ID',              'NUMBER(6)');
  P_ADD_COL('HRD_LEAVE_REQUEST', 'ASSIGNED_APPROVER_ID', 'NUMBER(10)');
  P_ADD_COL('HRD_LEAVE_REQUEST', 'ROUTED_AS',            'VARCHAR2(15)');
  P_ADD_COL('HRD_LEAVE_REQUEST', 'DECISION_REMARKS',     'VARCHAR2(500)');
  P_ADD_COL('HRD_LEAVE_REQUEST', 'CREATED_BY',           'VARCHAR2(100)');
  P_ADD_COL('HRD_LEAVE_REQUEST', 'CREATED_ON',           'DATE');
  P_ADD_COL('HRD_LEAVE_REQUEST', 'MODIFIED_BY',          'VARCHAR2(100)');
  P_ADD_COL('HRD_LEAVE_REQUEST', 'MODIFIED_ON',          'DATE');
  P_ADD_COL('HRD_LEAVE_REQUEST', 'ROW_VERSION',          'NUMBER(9) DEFAULT 1 NOT NULL');

  P_TRY('ALTER TABLE HRD.HRD_LEAVE_REQUEST ADD CONSTRAINT FK_LVREQ_WARD FOREIGN KEY (WARD_ID) REFERENCES HRD.HRD_WARD_MST (WARD_ID)');
  P_TRY('ALTER TABLE HRD.HRD_LEAVE_REQUEST ADD CONSTRAINT FK_LVREQ_APPROVER FOREIGN KEY (ASSIGNED_APPROVER_ID) REFERENCES HRD.HRD_EMPLOYEE_MST (EMPLOYEE_ID)');
  -- NOVALIDATE: existing rows are not checked (their LEAVE_TYPE codes and STATUS values are not known); new rows are.
  P_TRY('ALTER TABLE HRD.HRD_LEAVE_REQUEST ADD CONSTRAINT FK_LVREQ_TYPE FOREIGN KEY (LEAVE_TYPE) REFERENCES HRD.HRD_LEAVE_TYPE_MST (LEAVE_TYPE) ENABLE NOVALIDATE');
  P_TRY('ALTER TABLE HRD.HRD_LEAVE_REQUEST ADD CONSTRAINT CK_LVREQ_STATUS CHECK (STATUS IN (''SUBMITTED'',''APPROVED'',''REJECTED'')) ENABLE NOVALIDATE');
  P_TRY('ALTER TABLE HRD.HRD_LEAVE_REQUEST ADD CONSTRAINT CK_LVREQ_DATES CHECK (TO_DATE >= FROM_DATE) ENABLE NOVALIDATE');
  P_TRY('ALTER TABLE HRD.HRD_LEAVE_REQUEST ADD CONSTRAINT CK_LVREQ_ROUTED CHECK (ROUTED_AS IN (''WARD_HEAD'',''DNS'',''REPORTING_MGR'')) ENABLE NOVALIDATE');

  P_TRY('CREATE INDEX HRD.IDX_LVREQ_EMP_FROM ON HRD.HRD_LEAVE_REQUEST (EMPLOYEE_ID, FROM_DATE)');
  P_TRY('CREATE INDEX HRD.IDX_LVREQ_APPR_STATUS ON HRD.HRD_LEAVE_REQUEST (ASSIGNED_APPROVER_ID, STATUS)');
  P_TRY('CREATE INDEX HRD.IDX_LVREQ_WARD_FROM ON HRD.HRD_LEAVE_REQUEST (WARD_ID, FROM_DATE)');
  P_TRY('CREATE INDEX HRD.IDX_LVREQ_STATUS_DATES ON HRD.HRD_LEAVE_REQUEST (STATUS, FROM_DATE, TO_DATE)');
END;
/
